# NUMBERS
# Integers
wheat_flour = 20
refined_flour = 20
servings = 6
scale = 3

# Add
total_flour = wheat_flour + refined_flour
print(f"Total Flour in grams is : {total_flour}")

# Subtract
only_wheat_flour = total_flour - refined_flour
print(f"Wheat flour in grams is : {only_wheat_flour}")

# Multiply
mul_total_flour = wheat_flour * refined_flour
print(f"Multiplication of flour is : {mul_total_flour}")

# divide
div_flour = total_flour / servings
print(f"Combined flour served per serving : {div_flour}")

# divide (whole number)
whole_div_flour = total_flour // servings
print(f"Combined flour served per serving as whole : {whole_div_flour}")

# Remainder (modulus)
remaining_flour = total_flour % servings
print(f"Combined flour served per serving as whole : {remaining_flour}")

# Exponential
power_flour = total_flour ** scale
print(f"Powerful Flour : {power_flour}")

# Big Number
added_salt_particles = 100_000_000
print(f"Total salt particles : {added_salt_particles}")

